#!/usr/bin/env bash
# data for the lock screen (hyprlock): lock-info.sh art | track | artist | weather | vars
C="$HOME/.cache/sakura-lock"; mkdir -p "$C"
S="$HOME/.config/sakura/settings.json"
blank() { [ -f "$C/blank.png" ] || magick -size 2x2 xc:none "$C/blank.png" 2>/dev/null; echo "$C/blank.png"; }
st=$(playerctl status 2>/dev/null)
case "$1" in
  art)       # the cover of what is playing (a copy, so hyprlock can read it), or a transparent pixel
    [ "$st" = Playing ] || [ "$st" = Paused ] || { blank; exit; }
    u=$(playerctl metadata mpris:artUrl 2>/dev/null)
    key=$(printf '%s' "$u" | md5sum | cut -c1-12); out="$C/cover-$key.png"
    if [ ! -s "$out" ]; then
      case "$u" in
        file://*) magick "${u#file://}" -resize 240x240^ -gravity center -extent 240x240 "$out" 2>/dev/null ;;
        http*)    curl -s --max-time 4 "$u" -o "$C/dl" && magick "$C/dl" -resize 240x240^ -gravity center -extent 240x240 "$out" 2>/dev/null ;;
      esac
      find "$C" -name 'cover-*.png' ! -name "cover-$key.png" -delete 2>/dev/null
    fi
    [ -s "$out" ] && echo "$out" || blank ;;
  track)  [ -n "$st" ] && [ "$st" != Stopped ] && playerctl metadata --format '{{title}}' 2>/dev/null | cut -c1-40 ;;
  artist) [ -n "$st" ] && [ "$st" != Stopped ] && { s=$(playerctl metadata --format '{{artist}}' 2>/dev/null | cut -c1-40); [ "$st" = Paused ] && s="⏸  $s"; echo "$s"; } ;;
  weather)
    python3 -I - "$S" <<'PY'
import json, os, sys
try: c = json.load(open(sys.argv[1]))
except Exception: c = {}
try: w = json.load(open(os.path.expanduser("~/.cache/sakura-weather.json")))
except Exception: sys.exit()
ru = c.get("lang") == "ru"
code = w["current"]["weather_code"]; t = w["current"]["temperature_2m"]
names = [(0, "Clear", "Ясно"), (2, "Partly cloudy", "Переменная облачность"), (3, "Cloudy", "Облачно"), (48, "Fog", "Туман"), (57, "Drizzle", "Морось"),
         (67, "Rain", "Дождь"), (77, "Snow", "Снег"), (82, "Showers", "Ливни"), (86, "Snow showers", "Снегопад"), (999, "Thunderstorm", "Гроза")]
name = next((r if ru else e) for lim, e, r in names if code <= lim)
temp = f"{round(t * 9 / 5 + 32)}°F" if c.get("units") == "f" else f"{round(t)}°"
print(f"{temp}  {name} · {w.get('city', '')}")
PY
    ;;
  vars)      # monitor + wallpaper for this PC, read by hyprlock.conf through "source"
    eval "$(python3 -I - "$S" <<'PY'
import json, os, sys, subprocess
try: c = json.load(open(sys.argv[1]))
except Exception: c = {}
main = c.get("mainMonitor") or ""
try:
    ms = json.loads(subprocess.run(["hyprctl", "monitors", "-j"], capture_output=True, text=True).stdout)
    if not any(m["name"] == main for m in ms):
        main = next((m["name"] for m in ms if m["x"] == 0 and m["y"] == 0), ms[0]["name"])
except Exception: pass
wp = c.get("wallpaper") or os.path.expanduser("~/Pictures/Wallpapers/main.jpg")
print(f"MAIN='{main}'; WP='{wp}'")
PY
)"
    printf '# generated by hypr/scripts/lock-info.sh vars (lock.sh runs it before locking)\n$main = %s\n$wallpaper = %s\n' "$MAIN" "$WP" > "$C/vars.conf" ;;
esac
