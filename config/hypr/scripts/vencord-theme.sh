#!/usr/bin/env bash
# sakura mono - Discord (Vencord) theme that follows the rice: the glass palette, the accent color and the
# wallpaper (a blurred, darkened still of it as the app background, embedded in the CSS - Discord can't load
# file:// pictures). Writes ~/.config/Vencord/themes/sakura-mono.theme.css; Vencord reloads it live.
#   vencord-theme.sh [WALLPAPER]     (no arg = the one in settings.json)
# Called by accent.sh (accent changed) and wallpaper.sh (wallpaper changed); runs debounced in the background.
S="$HOME/.config/sakura/settings.json"
D="$(dirname "$(readlink -f "$0")")"
OUT="$HOME/.config/Vencord/themes/sakura-mono.theme.css"
CACHE="$HOME/.cache/sakura/vencord"
[ -d "$HOME/.config/Vencord" ] || exit 0
mkdir -p "$CACHE" "$(dirname "$OUT")"

# debounce: Settings previews wallpapers one after another - only the last call within 1.5 s does the work
tok="$CACHE/token"; me="$$-$(date +%s%N)"; echo "$me" > "$tok"; sleep 1.5
[ "$(cat "$tok" 2>/dev/null)" = "$me" ] || exit 0

wp="${1:-}"
[ -n "$wp" ] || wp=$(python3 -I -c 'import json,sys;print(json.load(open(sys.argv[1])).get("wallpaper",""))' "$S" 2>/dev/null)
[ -f "$wp" ] || wp="$HOME/Pictures/Wallpapers/main.jpg"
img=""
if [ -f "$wp" ]; then
    still=$("$D/wallpaper.sh" still "$wp" 2>/dev/null)
    if [ -f "$still" ]; then
        img="$CACHE/bg.jpg"
        magick "$still" -resize '1600x1600>' -blur 0x5 -modulate 120,110 -quality 78 -strip "$img" 2>/dev/null || img=""
    fi
fi

python3 -I - "$S" "$OUT" "$img" <<'PY'
import json, sys, os, base64, colorsys
S, OUT, IMG = sys.argv[1], sys.argv[2], sys.argv[3]
try: c = json.load(open(S))
except Exception: c = {}
acc = str(c.get("accent", "#f2b8d0")).lstrip("#")
font = c.get("font", "Inter")
glass = c.get("glass", 0.55)
glass = max(0.15, min(0.95, glass)) if isinstance(glass, (int, float)) else 0.55
r, g, b = (int(acc[i:i + 2], 16) for i in (0, 2, 4))
lum = 0.2126 * r / 255 + 0.7152 * g / 255 + 0.0722 * b / 255
acc_fg = "#1a121a" if lum > 0.55 else "#ffffff"
h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
def hls(hh, ll, ss): x = colorsys.hls_to_rgb(hh, ll, ss); return "%d, %d, %d" % tuple(round(v * 255) for v in x)
acc_rgb = "%d, %d, %d" % (r, g, b)
acc_dim = hls(h, max(0.0, l - 0.12), s)
# panels: the shell's glass (15,17,25); stronger alpha where text sits so it stays readable over the picture
a_side, a_main, a_float = round(min(0.8, glass * 0.95), 2), round(min(0.7, glass * 0.6), 2), round(min(0.9, glass + 0.2), 2)
bg = ""
if IMG and os.path.exists(IMG):
    bg = "url(data:image/jpeg;base64," + base64.b64encode(open(IMG, "rb").read()).decode() + ")"
css = f"""/**
 * @name sakura mono
 * @author sakura rice (auto)
 * @description Follows the desktop: glass palette, accent #{acc}, the wallpaper as background. Regenerated by ~/.config/hypr/scripts/vencord-theme.sh - edits here are overwritten.
 * @version 1.0.0
 */
:root {{
  --sk-acc: rgb({acc_rgb});
  --sk-acc-rgb: {acc_rgb};
  --sk-acc-dim: rgb({acc_dim});
  --sk-acc-fg: {acc_fg};
  --sk-glass: 15, 17, 25;
  --sk-bg: {bg or "none"};
  --font-primary: "{font}", "gg sans", "Noto Sans", sans-serif;
  --font-display: "{font}", "gg sans", "Noto Sans", sans-serif;
}}
.theme-dark, .theme-darker, .theme-midnight, .visual-refresh, .visual-refresh.theme-dark {{
  /* accent */
  --brand-500: var(--sk-acc); --brand-560: var(--sk-acc-dim); --brand-600: var(--sk-acc-dim);
  --brand-experiment: var(--sk-acc); --brand-experiment-560: var(--sk-acc-dim);
  --text-link: var(--sk-acc); --control-brand-foreground: var(--sk-acc); --control-brand-foreground-new: var(--sk-acc);
  --button-filled-brand-background: var(--sk-acc); --button-filled-brand-background-hover: var(--sk-acc-dim);
  --button-filled-brand-background-active: var(--sk-acc-dim); --button-filled-brand-text: var(--sk-acc-fg);
  --mention-foreground: var(--sk-acc); --mention-background: rgba(var(--sk-acc-rgb), .14);
  --background-mentioned: rgba(var(--sk-acc-rgb), .08); --background-mentioned-hover: rgba(var(--sk-acc-rgb), .12);
  --info-mentioned-border: var(--sk-acc); --status-positive-background: var(--sk-acc);
  --redesign-button-primary-background: var(--sk-acc); --redesign-button-primary-text: var(--sk-acc-fg);
  --redesign-button-primary-hover-background: var(--sk-acc-dim);
  /* glass surfaces (classic names) */
  --background-primary: rgba(var(--sk-glass), {a_main});
  --background-secondary: rgba(var(--sk-glass), {a_side});
  --background-secondary-alt: rgba(var(--sk-glass), {a_side});
  --background-tertiary: rgba(var(--sk-glass), {a_float});
  --background-accent: rgba(var(--sk-acc-rgb), .25);
  --background-floating: rgba(var(--sk-glass), .96);
  --background-nested-floating: rgba(var(--sk-glass), .96);
  --background-mobile-primary: rgba(var(--sk-glass), {a_main});
  --background-mobile-secondary: rgba(var(--sk-glass), {a_side});
  --channeltextarea-background: rgba(255, 255, 255, .06);
  --background-message-hover: rgba(255, 255, 255, .035);
  --background-modifier-hover: rgba(255, 255, 255, .06);
  --background-modifier-active: rgba(255, 255, 255, .09);
  --background-modifier-selected: rgba(var(--sk-acc-rgb), .16);
  --background-modifier-accent: rgba(255, 255, 255, .07);
  --deprecated-card-bg: rgba(255, 255, 255, .04);
  --modal-background: rgba(var(--sk-glass), .96); --modal-footer-background: rgba(var(--sk-glass), .9);
  --input-background: rgba(255, 255, 255, .06);
  --scrollbar-auto-thumb: rgba(255, 255, 255, .14); --scrollbar-thin-thumb: rgba(255, 255, 255, .14);
  --scrollbar-auto-track: transparent;
  /* glass surfaces (visual refresh names) */
  --background-base-lowest: rgba(var(--sk-glass), {a_float});
  --background-base-lower: rgba(var(--sk-glass), {a_side});
  --background-base-low: rgba(var(--sk-glass), {a_main});
  --background-surface-high: rgba(var(--sk-glass), .9);
  --background-surface-higher: rgba(var(--sk-glass), .94);
  --background-surface-highest: rgba(var(--sk-glass), .97);
  --chat-background-default: rgba(var(--sk-glass), {a_main});
  --bg-base-primary: rgba(var(--sk-glass), {a_main});
  --bg-base-secondary: rgba(var(--sk-glass), {a_side});
  --bg-base-tertiary: rgba(var(--sk-glass), {a_float});
  --bg-surface-raised: rgba(var(--sk-glass), .9);
  --bg-surface-overlay: rgba(var(--sk-glass), .96);
  --bg-overlay-1: transparent; --bg-overlay-2: transparent; --bg-overlay-3: transparent;
  --bg-overlay-4: transparent; --bg-overlay-5: transparent; --bg-overlay-6: transparent;
  --bg-overlay-chat: transparent; --bg-overlay-app-frame: rgb(var(--sk-glass)); --bg-overlay-floating: rgba(var(--sk-glass), .96);
  --bg-brand: var(--sk-acc);
  --border-subtle: rgba(255, 255, 255, .06); --border-faint: rgba(255, 255, 255, .04);
  --border-normal: rgba(255, 255, 255, .08); --border-strong: rgba(255, 255, 255, .12);
  --app-frame-background: rgb(var(--sk-glass)); --app-border-frame: rgba(255, 255, 255, .06);
  /* text */
  --text-normal: #e6e8ef; --text-default: #e6e8ef; --header-primary: #f4f5f8; --header-secondary: #b6bac6;
  --text-muted: #8b90a0; --channels-default: #9ea3b2; --interactive-normal: #b6bac6;
  --interactive-hover: #eef0f5; --interactive-active: #ffffff; --interactive-muted: #5b6070;
}}
/* the wallpaper behind everything */
html, body, #app-mount {{
  background: rgb(var(--sk-glass)) var(--sk-bg) center / cover no-repeat fixed !important;
}}
#app-mount [class*="bg_"], #app-mount [class^="bg_"] {{ background: transparent !important; }}
[class*="appMount"], [class*="app_"], [class*="app-"], [class*="layers_"], [class*="layer_"]:not([class*="baseLayer"] ~ *),
[class*="container_"][class*="themed_"], [class*="base_"] {{ background: transparent !important; }}
/* accent bits */
[class*="unread_"], [class*="item_"][class*="selected"]::before {{ background-color: var(--sk-acc) !important; }}
::selection {{ background: rgba(var(--sk-acc-rgb), .35); }}
[class*="numberBadge"], [class*="mentionsBadge"] {{ background-color: var(--sk-acc) !important; color: var(--sk-acc-fg) !important; }}
/* top bar (title, search, inbox) and the channel header: solid, no wallpaper showing through */
div[class*="base_"] > div[class*="bar_"], [class*="titleBar_"], [class*="typeWindows_"],
[class*="chat_"] > section[class*="title_"], section[class*="title_"][class*="container_"] {{
  background: rgb(var(--sk-glass)) !important;
}}
/* bottom-left block (voice connection + your account): one solid glass card instead of see-through strips */
section[class*="panels_"] {{
  background: rgba(var(--sk-glass), {a_float}) !important;
  backdrop-filter: blur(18px) saturate(1.2);
  border: 1px solid rgba(255, 255, 255, .07) !important;
  border-radius: 14px !important; box-shadow: 0 6px 24px rgba(0, 0, 0, .35) !important;
  overflow: hidden;
}}
section[class*="panels_"] > div, section[class*="panels_"] [class*="container_"],
section[class*="panels_"] [class*="wrapper_"], section[class*="panels_"] [class*="connection_"] {{ background: transparent !important; }}
section[class*="panels_"] [class*="actionButtons_"] button, section[class*="panels_"] [class*="button_"][class*="buttonColor"] {{
  background: rgba(255, 255, 255, .06) !important; border-radius: 10px !important;
}}
section[class*="panels_"] [class*="actionButtons_"] button:hover {{ background: rgba(var(--sk-acc-rgb), .18) !important; }}
/* softer corners like the shell */
[class*="channelTextArea"] [class*="scrollableContainer"], [class*="channelTextArea"] > [class*="inner"] {{ border-radius: 14px !important; }}
[class*="menu_"], [class*="popout"], [class*="tooltip_"] {{ border-radius: 12px !important; }}
"""
# Discord sets its own variables with higher specificity: make ours win
import re as _re
def _imp(block): return _re.sub(r"(--[\w-]+:\s*[^;{}]+?)\s*;", lambda m: m.group(1) + (";" if "!important" in m.group(1) else " !important;"), block)
css = _re.sub(r"(\.theme-dark, \.theme-darker[^{]*\{)([^}]*)\}", lambda m: m.group(1) + _imp(m.group(2)) + "}", css, count=1)
tmp = OUT + ".tmp"
open(tmp, "w").write(css); os.replace(tmp, OUT)
PY

# switch it on in Vencord once (Vencord writes settings.json itself while Discord runs; only add, never remove)
python3 -I - "$HOME/.config/Vencord/settings/settings.json" <<'PY'
import json, sys, os
p = sys.argv[1]
try: d = json.load(open(p))
except Exception: sys.exit()
t = d.get("enabledThemes") or []
if "sakura-mono.theme.css" not in t:
    d["enabledThemes"] = t + ["sakura-mono.theme.css"]
    open(p + ".tmp", "w").write(json.dumps(d, indent=4, ensure_ascii=False)); os.replace(p + ".tmp", p)
PY
