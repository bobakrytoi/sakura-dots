              "kamoso,QtCreator,VirtualBox,VirtualBoxVM,trojita,dragon,digikam,lyx,ayugram-desktop,telegram-desktop,"
              "openrgb,obs,krita,okular,gwenview,konsole,yakuake,steam,mpv,kate,kwrite",
