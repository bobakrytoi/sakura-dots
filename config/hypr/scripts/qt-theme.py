#!/usr/bin/env python3
"""Sakura look for Qt / KDE apps (Dolphin first of all), generated from the accent in settings.json.
  qt-theme.py            -> regenerate everything from ~/.config/sakura/settings.json "accent"
  qt-theme.py '#rrggbb'  -> same, with this accent
Writes:
  ~/.config/Kvantum/Sakura/Sakura.{kvconfig,svg}   (based on the stock KvArcDark, recolored; translucent windows
                                                    so Hyprland blur shows through, accent selection with alpha)
  ~/.config/Kvantum/kvantum.kvconfig               (theme=Sakura)
  ~/.local/share/color-schemes/Sakura.colors + the [Colors:*] groups of ~/.config/kdeglobals
                                                    (KDE apps take their palette from here, not from qt6ct)
  ~/.config/qt6ct/colors/sakura.conf               (palette for qt6ct; style switched to kvantum)
Called by hypr/scripts/accent.sh on every accent change. GTK is not touched."""
import colorsys, configparser, json, os, re, sys

H = os.path.expanduser("~")
S = os.path.join(H, ".config/sakura/settings.json")
BASE = "/usr/share/Kvantum/KvArcDark/KvArcDark"
KV = os.path.join(H, ".config/Kvantum")
OUT = os.path.join(KV, "Sakura")

def accent():
    if len(sys.argv) > 1 and re.fullmatch(r"#?[0-9a-fA-F]{6}", sys.argv[1]):
        return "#" + sys.argv[1].lstrip("#").lower()
    try: return json.load(open(S)).get("accent", "#f2b8d0").lower()
    except Exception: return "#f2b8d0"

ACC = accent()
def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
def hexc(r, g, b): return "#%02x%02x%02x" % tuple(max(0, min(255, round(v))) for v in (r, g, b))
def hls(h): return colorsys.rgb_to_hls(*(v / 255 for v in rgb(h)))
def from_hls(h, l, s): return hexc(*(v * 255 for v in colorsys.hls_to_rgb(h, max(0, min(1, l)), max(0, min(1, s)))))
AH, AL, AS = hls(ACC)
ACC_DIM = from_hls(AH, AL * 0.86, AS * 0.75)            # pressed / darker accent
ACC_TXT = "#11131b"                              # text on a solid (pastel) accent

# palette of the shell (HANDOFF 1.4): glass #0f1119 @ 55 %, cards = white overlays
GLASS, BG, BASE_C, ALT, BTN = "#0f1119", "#0f1119", "#141722", "#181b26", "#1d2030"
FG, MUTED, DIS = "#eceef4", "#8a8fa3", "#5b6075"

def save(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"; open(tmp, "w").write(text); os.replace(tmp, path)

# ── Kvantum SVG: recolor KvArcDark ─────────────────────────────────────────
def recolor(m):
    c = m.group(0).lower()
    h, l, s = hls(c)
    if s > 0.45 and 0.52 < h < 0.65:                          # Arc's blue accent family → our accent
        return from_hls(AH, AL + (l - 0.60) * 0.6, AS)
    if s < 0.25 and 0.55 < h < 0.72 and 0.05 < l < 0.45:      # Arc's slate greys → our deeper blue-black
        return from_hls(0.64, l * 0.52, min(0.30, s + 0.05))
    return c

svg = open(BASE + ".svg").read()
svg = re.sub(r"#[0-9a-fA-F]{6}\b", recolor, svg)
acc_l = ACC.lower()
# selections & pressed buttons: translucent accent (glass), so white text stays readable on any accent
SOFT = re.compile(r"^(itemview|menuitem|menubaritem|header|button|tbutton|tab)-(toggled|pressed|focused)")
def soften(m):
    tag = m.group(0)
    i = re.search(r'\bid="([^"]+)"', tag)
    fills = re.findall(r'fill[:=]"?(#[0-9a-fA-F]{6})', tag)
    if not i or not SOFT.match(i.group(1)) or not fills or hls(fills[0].lower())[2] < 0.3: return tag   # accent-coloured only
    if i.group(1).startswith("itemview"):          # files: translucent accent, light text stays readable
        a = "0.16" if "focused" in i.group(1) else "0.34"     # (Dolphin's details view keeps normal text on selection)
    elif i.group(1).startswith(("menuitem", "menubaritem")): a = "0.88"   # menus: solid pastel + dark text
    else: a = "0.55"
    tag = re.sub(r"fill-opacity:[0-9.]+;?", "", tag)
    tag = re.sub(r"(fill:#[0-9a-fA-F]{6})", r"\1;fill-opacity:" + a, tag, count=1)
    tag = re.sub(r'(fill="#[0-9a-fA-F]{6}")', r'\1 fill-opacity="' + a + '"', tag, count=1)
    return tag
svg = re.sub(r"<(?:rect|path|circle|ellipse)\b[^>]*>", soften, svg, flags=re.S)
save(os.path.join(OUT, "Sakura.svg"), svg)

# ── Kvantum kvconfig ───────────────────────────────────────────────────────
kv = open(BASE + ".kvconfig").read()
kv = re.sub(r"#[0-9a-fA-F]{6}\b", recolor, kv)
def setkey(text, section, key, val):
    pat = re.compile(r"(^\[" + re.escape(section) + r"\]\n)(.*?)(?=^\[|\Z)", re.S | re.M)
    m = pat.search(text)
    if not m: return text + f"\n[{section}]\n{key}={val}\n"
    body = m.group(2)
    if re.search(r"^" + re.escape(key) + r"=", body, re.M):
        body = re.sub(r"^" + re.escape(key) + r"=.*$", f"{key}={val}", body, flags=re.M)
    else:
        body = f"{key}={val}\n" + body
    return text[:m.start(2)] + body + text[m.end(2):]
