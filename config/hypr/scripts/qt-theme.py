kv = setkey(kv, "ItemView", "text.normal.color", FG)
for sec in ("MenuItem", "MenuBarItem"):          # dark text on the (always pastel) accent
    for k in ("text.press.color", "text.toggle.color"): kv = setkey(kv, sec, k, ACC_TXT)
save(os.path.join(OUT, "Sakura.kvconfig"), kv)
save(os.path.join(KV, "kvantum.kvconfig"), "[General]\ntheme=Sakura\n")

