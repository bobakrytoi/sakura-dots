#!/usr/bin/env bash
# move the top bar down next to the dock and back:  barpos.sh top | bottom | toggle | gen
# the choice is remembered in ~/.config/sakura/barpos; waybar.sh picks the matching config.
# "gen" (also run by waybar.sh) rebuilds config-bottom.jsonc for the monitors this PC actually has.
S="$HOME/.config/sakura/barpos"
gen() {
  hyprctl monitors -j | python3 -I -c '
import json, os, sys
ms = json.load(sys.stdin)
try: cfg = json.load(open(os.path.expanduser("~/.config/sakura/settings.json")))
except Exception: cfg = {}
main = cfg.get("mainMonitor") or ""
H = "%H:%M" if cfg.get("clock24", True) is not False else "%I:%M %p"
if cfg.get("seconds"): H = H.replace("%M", "%M:%S")
m = next((x for x in ms if x["name"] == main), None) or next((x for x in ms if x["x"] == 0 and x["y"] == 0), None) or ms[0]
W = round(m["width"] / m["scale"])
others = [x["name"] for x in ms if x["name"] != m["name"]]
inc = ["~/.config/waybar/config.jsonc"]
up = {"format": "", "tooltip-format": "Move the bar back to the top", "on-click": "$HOME/.config/hypr/scripts/barpos.sh top"}
# two pills on both sides of the dock, in the dock row (the dock reserves 72px; -64 puts the pills back into it)
pill = {"include": inc, "output": m["name"], "position": "bottom", "layer": "top", "exclusive": False,
        "height": 60, "margin-top": 0, "margin-bottom": -64}
left = dict(pill, name="waybar-left", **{"margin-left": 14, "margin-right": max(14, W - 14 - 520),
        "modules-left": ["custom/barpos", "clock", "image#cover", "mpris", "custom/minimized"], "modules-center": [], "modules-right": [],
        "clock": {"format": "<b>{:L" + H + "</b>\n<span color=\x27#8a8fa3\x27 size=\x27small\x27>%a, %d %b}</span>",
                  "tooltip-format": "<b>{:L%A, %d %B %Y}</b>", "on-click": "qs ipc call dashboard toggle",
                  **({"locale": {"ru": "ru_RU.UTF-8", "uk": "uk_UA.UTF-8"}[cfg["lang"]]} if cfg.get("lang") in ("ru", "uk") else {})},
        "custom/barpos": up})
right = dict(pill, name="waybar-right", **{"margin-left": max(14, W - 14 - 720), "margin-right": 14,
        "modules-left": [], "modules-center": [],
        "modules-right": ["custom/capture", "group/traybox", "custom/layout", "pulseaudio", "network", "cpu", "memory", "custom/updates", "custom/notify", "custom/power"]})
# the other monitors keep the quickshell top bar (TopBar.qml)
bars = [left, right]
out = os.path.expanduser("~/.config/waybar/config-bottom.jsonc")
with open(out + ".tmp", "w") as f:
    f.write("// generated by ~/.config/hypr/scripts/barpos.sh for this PC\x27s monitors - edit the script, not this file\n")
    json.dump(bars, f, indent=2, ensure_ascii=False)
os.replace(out + ".tmp", out)
'
}
case "${1:-toggle}" in gen) gen; exit 0 ;; esac
cur=$(cat "$S" 2>/dev/null || echo top)
want=${1:-toggle}
if [ "$want" = toggle ]; then [ "$cur" = bottom ] && want=top || want=bottom; fi
[ "$want" = "$cur" ] && exit 0
mkdir -p "$(dirname "$S")"
echo "$want" > "$S"
touch "${XDG_RUNTIME_DIR:-/tmp}/waybar-switch"   # tells waybar.sh this exit is on purpose: restart at once
pkill -x waybar
