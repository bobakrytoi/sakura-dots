#!/usr/bin/env bash
# accent color for the whole rice:  accent.sh set '#f2b8d0' | auto | get | pick | apply '#hex'
#   set/auto: save it in settings.json and recolor everything (for the terminal)
#   pick:     just print a color picked from the wallpaper
#   apply:    recolor the other apps only (Settings saves settings.json itself - two writers raced before)
#   quickshell (menu, dock, settings, widgets…) reads it live from ~/.config/sakura/settings.json;
#   this script also rewrites the colors of waybar, notifications, rofi, kitty, hyprlock, the task manager
#   and window borders, and reloads them. "auto" picks a vivid color from the current wallpaper.
S="$HOME/.config/sakura/settings.json"
case "$1" in
  get) python3 -I -c 'import json,sys;print(json.load(open(sys.argv[1])).get("accent","#f2b8d0"))' "$S" 2>/dev/null || echo "#f2b8d0"; exit 0 ;;
  auto|pick)
    wp=$(python3 -I -c 'import json,sys;print(json.load(open(sys.argv[1])).get("wallpaper",""))' "$S" 2>/dev/null)
    [ -f "$wp" ] || wp="$HOME/Pictures/Wallpapers/main.jpg"
    case "${wp,,}" in *.mp4|*.webm|*.mkv|*.mov) wp=$("$(dirname "$(readlink -f "$0")")/wallthumb.sh" "$wp" 320) ;; esac   # a frame of a video wallpaper
    hex=$(magick "$wp" -resize 96x96 -colors 24 -format '%c' histogram:info:- 2>/dev/null | python3 -I -c '
import sys, re, colorsys
cols = []
for line in sys.stdin:
    m = re.search(r"^\s*(\d+):.*#([0-9A-Fa-f]{6})", line)
    if not m: continue
    n, hx = int(m.group(1)), m.group(2)
    r, g, b = (int(hx[i:i+2], 16) / 255 for i in (0, 2, 4))
    cols.append((n,) + colorsys.rgb_to_hls(r, g, b))
def pick(min_s):
    best, bs = None, -1
    for n, h, l, s in cols:
        if s < min_s or l < 0.10 or l > 0.94: continue
        score = n * (s ** 1.5) * (1 - abs(l - 0.6))
        if score > bs: best, bs = (h, l, s), score
    return best
best = pick(0.18)
if best is not None:
    h, l, s = best
    # soft pastel like the default sakura pink: light, gently saturated
    r, g, b = colorsys.hls_to_rgb(h, 0.80, max(0.55, min(0.85, s + 0.25)))
else:
    # a grey / washed-out wallpaper: keep its faint tint, as a calm pale color (not the default pink)
    best = pick(0.02)
    if best is None: print("#c8ccd8"); sys.exit()
    h, l, s = best
    r, g, b = colorsys.hls_to_rgb(h, 0.82, max(0.28, min(0.45, s * 3)))
print("#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255)))')
    [ "$1" = pick ] && { echo "$hex"; exit 0; }
    exec "$0" set "$hex" ;;
  set|apply) hex=$(printf '%s' "$2" | tr 'A-F' 'a-f'); [[ "$hex" =~ ^#?[0-9a-f]{6}$ ]] || { echo "usage: accent.sh set '#rrggbb'"; exit 1; }; hex="#${hex#\#}" ;;
  *) echo "usage: accent.sh set '#rrggbb' | auto | get"; exit 1 ;;
esac
python3 -I - "$S" "$hex" "$1" <<'PY'
import json, os, re, sys
S, hx, mode = sys.argv[1], sys.argv[2], sys.argv[3]; h6 = hx[1:]
H = os.path.expanduser("~")
def sub(path, pat, rep, flags=re.M):
    p = os.path.join(H, path)
    if not os.path.exists(p): return
    t = open(p).read(); n = re.sub(pat, rep, t, flags=flags)
    if n != t: open(p + ".tmp", "w").write(n); os.replace(p + ".tmp", p)
try: skip = json.load(open(S)).get("accentSkip", [])     # Settings > Appearance: apps that keep their own colors
except Exception: skip = []
_sub = sub
def sub(path, *a, **k):
    for name, part in (("rofi", "rofi/"), ("hyprlock", "hyprlock"), ("waybar", "waybar/")):
        if name in skip and part in path: return
    _sub(path, *a, **k)
if mode == "set":
    try: c = json.load(open(S))
    except Exception: c = {}
    c["accent"] = hx
    open(S + ".tmp", "w").write(json.dumps(c, indent=2, ensure_ascii=False)); os.replace(S + ".tmp", S)
sub(".config/waybar/style.css", r"^@define-color accent\s+#[0-9a-fA-F]{6};", "@define-color accent  " + hx + ";")
sub(".config/swaync/style.css", r"^@define-color accent\s+#[0-9a-fA-F]{6};", "@define-color accent  " + hx + ";")
sub(".config/rofi/colors.rasi", r"^(\s*accent:\s*)#[0-9a-fA-F]{6};", r"\g<1>" + hx + ";")
sub(".config/hypr/hyprlock.conf", r"^\$accent = rgb\([0-9a-fA-F]{6}\)", "$accent = rgb(" + h6 + ")")
sub(".config/hypr/hyprlock.conf", r"rgba\([0-9a-fA-F]{6}ee\)", "rgba(" + h6 + "ee)")
if "mpv" not in skip:   # mpv player UI (uosc): progress bar / highlights; applies to the next opened video
    sub(".config/mpv/script-opts/uosc.conf", r"^(color=foreground=)[0-9a-fA-F]{6}(.*,match=)[0-9a-fA-F]{6}(,heatmap=)[0-9a-fA-F]{6}", r"\g<1>" + h6 + r"\g<2>" + h6 + r"\g<3>" + h6)
k = os.path.join(H, ".config/kitty")
if os.path.isdir(k) and "kitty" not in skip:
    open(os.path.join(k, "accent.conf"), "w").write(
        "# generated by hypr/scripts/accent.sh - the accent color from Settings\n"
        f"selection_background  {hx}\ncursor                {hx}\nurl_color             {hx}\nactive_tab_background   {hx}\ncolor5  {hx}\n")
    kc = os.path.join(k, "kitty.conf"); t = open(kc).read()
    if "include accent.conf" not in t: open(kc, "a").write("\n# accent color from Settings (hypr/scripts/accent.sh)\ninclude accent.conf\n")
PY
swaync-client -rs >/dev/null 2>&1
pkill -USR1 -x kitty 2>/dev/null
[ "$1" = apply ] && sleep 0.6           # let Settings finish writing settings.json first
hyprctl reload >/dev/null 2>&1          # window borders (hyprland.lua reads the accent from settings.json)
"$(dirname "$(readlink -f "$0")")/sddm-sync.sh" accent "$hex" >/dev/null 2>&1 &   # the SDDM login screen
"$(dirname "$(readlink -f "$0")")/settings-icon.sh" "$hex" >/dev/null 2>&1 &       # Settings app icon (accent gear)
setsid -f "$(dirname "$(readlink -f "$0")")/vencord-theme.sh" >/dev/null 2>&1        # Discord (Vencord) theme
# Qt / KDE apps (Dolphin, Ark…): Kvantum theme "Sakura" + kdeglobals colors; already open windows recolor on restart
{ python3 -I "$(dirname "$(readlink -f "$0")")/qt-theme.py" "$hex" >/dev/null 2>&1 &&
  dbus-send --session --type=signal /KGlobalSettings org.kde.KGlobalSettings.notifyChange int32:0 int32:0 2>/dev/null; } &
echo "$hex"
